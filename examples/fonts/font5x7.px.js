// One row of 5x7 cells, in the order of CHARS.
sprite("_font5x7", { w: CHARS.length * 5, h: 7 }, (c) =>
  [...CHARS].forEach((ch, i) => c.grid(i * 5, 0, GLYPHS[ch].split(" ").join("\n").replace(/#/g, "k"))))
font("5x7", "_font5x7", { chars: CHARS, w: 5, h: 7 })

